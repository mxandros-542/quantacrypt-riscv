"""Generate deterministic TEST-ONLY vectors and the ML-DSA twiddle ROM."""

import argparse
import hashlib
import json
from pathlib import Path
import random

from reference_model import N, Q, ROOT, ZETAS, intt, intt_direct, ntt, ntt_direct

PROJECT = Path(__file__).resolve().parents[1]


def input_cases():
    cases = [
        ("zero", [0] * N),
        ("ones", [1] * N),
        ("q_minus_one", [Q - 1] * N),
    ]
    for position in (0, 1, 255):
        a = [0] * N
        a[position] = 1
        cases.append((f"impulse_{position}", a))
    cases.extend([
        ("ramp", list(range(N))),
        ("alternating_extremes", [0, Q - 1] * (N // 2)),
        ("eta2_signed", [((i % 5) - 2) % Q for i in range(N)]),
    ])
    for seed in (44001, 44002, 44003):
        rng = random.Random(seed)  # Reproducible verification data, never masks for deployment.
        cases.append((f"uniform_seed_{seed}", [rng.randrange(Q) for _ in range(N)]))
    return cases


def rom_source():
    lines = [
        "`timescale 1ns/1ps",
        "// Generated by tools/generate_vectors.py from FIPS 204 Algorithms 41/43.",
        "// Standard-domain zeta[k] = 1753^BitRev8(k) mod 8380417. Index 0 is unused.",
        "module ntt_twiddle_rom (",
        "  input  logic [7:0]  index_i,",
        "  output logic [22:0] zeta_o",
        ");",
        "  always_comb begin",
        "    case (index_i)",
    ]
    lines.extend(f"      8'd{k}: zeta_o = 23'd{zeta};" for k, zeta in enumerate(ZETAS))
    lines.extend([
        "      default: zeta_o = 23'd1;",
        "    endcase",
        "  end",
        "endmodule",
        "",
    ])
    return "\n".join(lines)


def generate(output_dir, rom_path):
    output_dir.mkdir(parents=True, exist_ok=True)
    inputs, expected, modes, manifest_cases = [], [], [], []
    for name, a in input_cases():
        for mode, transform, direct in ((0, ntt, ntt_direct), (1, intt, intt_direct)):
            result = direct(a)
            if transform(a) != result:
                raise AssertionError(f"butterfly/direct mismatch for {name}, mode={mode}")
            manifest_cases.append({
                "index": len(modes), "name": name,
                "mode": "inverse" if mode else "forward",
                "coefficient_offset": len(inputs),
            })
            modes.append(mode)
            inputs.extend(a)
            expected.extend(result)
    files = {
        "input.memh": "".join(f"{value:06x}\n" for value in inputs),
        "expected.memh": "".join(f"{value:06x}\n" for value in expected),
        "modes.memh": "".join(f"{value:x}\n" for value in modes),
        "vector_count.svh": f"`define NTT_VECTOR_COUNT {len(modes)}\n",
    }
    for name, contents in files.items():
        (output_dir / name).write_text(contents, encoding="ascii")
    manifest = {
        "num_cases": len(modes), "n": N, "q": Q, "root": ROOT,
        "representation": "canonical unsigned standard domain; bit-reversed odd roots",
        "expected_oracle": "independent O(N^2) Horner evaluation / inverse interpolation",
        "randomness": "deterministic TEST-ONLY Python Random seeds",
        "cases": manifest_cases,
        "sha256": {name: hashlib.sha256(contents.encode("ascii")).hexdigest()
                   for name, contents in files.items()},
    }
    (output_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="ascii")
    rom_path.parent.mkdir(parents=True, exist_ok=True)
    rom_path.write_text(rom_source(), encoding="ascii")
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=PROJECT / "build" / "vectors")
    parser.add_argument("--rom-path", type=Path, default=PROJECT / "rtl" / "ntt_twiddle_rom.sv")
    args = parser.parse_args()
    result = generate(args.output_dir, args.rom_path)
    print(f"Generated {result['num_cases']} independently checked NTT/INTT cases and twiddle ROM.")


if __name__ == "__main__":
    main()
